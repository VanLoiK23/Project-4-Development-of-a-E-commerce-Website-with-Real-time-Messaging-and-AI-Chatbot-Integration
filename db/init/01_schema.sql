-- 3. Products & variants (masp đánh số tuần tự 1, 2, 3...)
-- =====================================================================
CREATE TABLE sanpham (
    masp            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tensp           VARCHAR(255),
    alias           VARCHAR(255) NOT NULL,
    hinhanh         VARCHAR(500),
    xuatxu          INTEGER,
    thuonghieu      INTEGER,
    khuvuckho       INTEGER,
    soluongnhap     INTEGER DEFAULT 0,
    soluongban      INTEGER DEFAULT 0,
    promo           TEXT,
    collections     jsonb NOT NULL DEFAULT '[]'::jsonb,
    sort_desc       VARCHAR(10000) NOT NULL DEFAULT '',
    detail          TEXT           NOT NULL DEFAULT '',
    tongsao         DOUBLE PRECISION NOT NULL DEFAULT 0,
    soluongdanhgia  INTEGER        NOT NULL DEFAULT 0,
    created         TIMESTAMP      NOT NULL DEFAULT now(),
    created_by      VARCHAR(100)   NOT NULL DEFAULT 'importer',
    modified        TIMESTAMP      NOT NULL DEFAULT now(),
    modified_by     VARCHAR(100)   NOT NULL DEFAULT 'importer',
    trash           VARCHAR(10)    NOT NULL DEFAULT 'active',
    deleted_at      DATE,
    status          INTEGER        NOT NULL DEFAULT 1,
    specs           JSONB          DEFAULT '{}'::jsonb,
    CONSTRAINT fk_sanpham_xuatxu     FOREIGN KEY (xuatxu)     REFERENCES xuatxu (maxuatxu),
    CONSTRAINT fk_sanpham_thuonghieu FOREIGN KEY (thuonghieu) REFERENCES thuonghieu (mathuonghieu),
    CONSTRAINT fk_sanpham_khuvuckho  FOREIGN KEY (khuvuckho)  REFERENCES khuvuckho (makhuvuc),
    CONSTRAINT chk_sanpham_specs_is_object CHECK (specs IS NULL OR jsonb_typeof(specs) = 'object')
);

COMMENT ON COLUMN sanpham.specs IS
'Technical specs as a flat JSON object. Keys (omit a key when unknown, never fake it): '
'os(text), release_year(int), chipset(text), expandable_storage(bool), battery_mah(int), charge_w(number), '
'screen_inch(number), resolution_w(int), resolution_h(int), panel(text: AMOLED/IPS/...), refresh_hz(int), '
'brightness_nits_peak(int), rear_main_mp(number), ois(bool), weight_g(number), ip_rating(text), nfc(bool), '
'has_5g(bool), wifi_gen(text), stereo_speaker(bool), headphone_jack(bool), source_url(text), scraped_at(text), benchmark_antutu(int), dxomark_camera(number)';

