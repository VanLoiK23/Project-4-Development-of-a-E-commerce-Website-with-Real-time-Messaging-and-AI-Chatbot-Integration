-- 4. Cart
-- =====================================================================
CREATE TABLE cart (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idkh        INTEGER   NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP NOT NULL DEFAULT now(),
    status      VARCHAR(20) DEFAULT 'active',
    CONSTRAINT fk_cart_khachhang FOREIGN KEY (idkh) REFERENCES khachhang (makh),
    CONSTRAINT chk_cart_status CHECK (status IN ('active', 'completed', 'abandoned'))
);
CREATE TRIGGER trg_cart_updated_at BEFORE UPDATE ON cart
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE cartitems (
    cart_item_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id       INTEGER NOT NULL,
    maphienbansp  INTEGER NOT NULL,
    soluong       INTEGER NOT NULL,
    CONSTRAINT fk_cartitems_cart        FOREIGN KEY (cart_id)      REFERENCES cart (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_cartitems_phienbansp  FOREIGN KEY (maphienbansp) REFERENCES phienbansanpham (maphienbansp)
        ON DELETE CASCADE ON UPDATE CASCADE
);

