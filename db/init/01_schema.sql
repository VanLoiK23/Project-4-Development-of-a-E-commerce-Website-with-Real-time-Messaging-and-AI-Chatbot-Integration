CREATE UNIQUE INDEX uq_sanpham_alias_active ON sanpham (alias) WHERE trash = 'active';
CREATE UNIQUE INDEX uq_taikhoan_email_live    ON taikhoan (lower(email))
    WHERE status IS DISTINCT FROM 'deleted';
